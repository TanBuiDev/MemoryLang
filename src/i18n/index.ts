export const uiLanguageOptions: Array<{ code: UiLanguageCode; label: string }> = [
  { code: 'vi', label: 'Vietnamese' },
  { code: 'en', label: 'English' },
]

export function getDefaultUiLanguage(nativeLanguage: LanguageCode): UiLanguageCode {
  return nativeLanguage === 'vi' ? 'vi' : 'en'
}

export function createTranslator(language: UiLanguageCode) {
  return (key: string, params: Record<string, string | number> = {}) => {
    const template = translations[language][key] ?? translations.en[key] ?? key
    return Object.entries(params).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), template)
  }
}

export function useI18n() {
  const profile = useAuthStore((state) => state.profile)
  const localUiLanguage = useUiLanguageStore((state) => state.uiLanguage)
  const language = localUiLanguage ?? profile?.ui_language ?? getDefaultUiLanguage(profile?.native_language ?? 'vi')
  return { language, t: createTranslator(language) }
}
